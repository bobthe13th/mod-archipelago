-- BarrensBeater realm setup: ilvl~10 grey starting kits per class, so a
-- character starting at level 10 (StartPlayerLevel=10) isn't stuck with only
-- their vanilla level-1 kit. This table (`playercreateinfo_item`) had no real
-- content in this checkout before this migration (only one unrelated leftover
-- placeholder row for race=0/class=6) -- Archipelago's own design philosophy
-- intentionally avoids handing out non-randomized gear, so this is a
-- deliberate, requested exception for BarrensBeater's level-10 start, not a
-- restoration of removed content.
--
-- One weapon + 3 armor pieces (chest/legs/hands) per class, all real,
-- existing Quality=0 (grey/Poor) items already in item_template with
-- ItemLevel in the 7-12 range (confirmed live via SELECT against this
-- checkout's own acore_world DB) -- no new items authored. Armor is Leather
-- for physical/hybrid classes and Cloth for the three pure casters (Priest/
-- Mage/Warlock), chosen for guaranteed equippability at level 10 regardless
-- of a class's eventual (higher-level) mail/plate proficiency. No grey-
-- quality Wand exists in this ItemLevel band, so Priest/Mage/Warlock get a
-- Staff instead (a normal, common vanilla caster starting-weapon choice).
--
-- Caveat: Death Knight is included for completeness (every real (race,class)
-- pair from the same 62-pair roster this realm's own playercreateinfo
-- migration uses), but this realm's StartHeroicPlayerLevel is 55 (reverted
-- after the ilvl-10 attempt broke DK level-10 stats, see this realm's own
-- worldserver.conf history) -- a real Death Knight on this realm starts at
-- 55, not 10, so this Leather ilvl~10 kit doesn't reflect their actual
-- starting level. Left in only for roster consistency; harmless (INSERT
-- IGNORE, an unused row costs nothing).
--
-- Item choices (all Quality=0, ItemLevel 7-12, confirmed live, none
-- "Deprecated"/"Test"):
--   Warrior/Paladin/Hunter/Rogue/Shaman/Druid/DK -> Leather: 1425 (chest),
--     1423 (legs), 1422 (hands); weapon varies by class (see below).
--   Priest/Mage/Warlock -> Cloth: 1433 (chest), 1431 (legs), 1430 (hands);
--     Staff weapon (1411 or 1515).
--   Weapons: Warrior 1413 (1H Sword), Paladin 1415 (1H Mace), Hunter 2773
--     (Bow), Rogue 2138 (Dagger), Priest 1411 (Staff), Death Knight 1412
--     (2H Sword), Shaman 2056 (1H Mace), Mage 1515 (Staff), Warlock 1411
--     (Staff), Druid 1414 (2H Mace).
--
-- INSERT IGNORE is idempotent against this table's real PK (race, class,
